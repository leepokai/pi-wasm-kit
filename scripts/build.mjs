import { build } from 'esbuild';
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
await rm('dist', { recursive: true, force: true });
await mkdir('dist', { recursive: true });
await build({ entryPoints: ['src/guest/entry.ts'], outfile: 'dist/guest.js', bundle: true, format: 'iife', platform: 'browser', target: 'es2022', legalComments: 'eof', metafile: true }).then(async result => {
  await writeFile('dist/guest-meta.json', JSON.stringify(result.metafile));
});
const source = await readFile('dist/guest.js', 'utf8');
await writeFile('src/guest-source.ts', '// Generated by scripts/build.mjs.\nconst source: string = ' + JSON.stringify(source) + ';\nexport default source;\n');
await build({ entryPoints: ['src/index.ts','src/storage/node.ts','src/storage/browser.ts','src/providers/openai.ts'], outdir: 'dist', outbase: 'src', bundle: false, format: 'esm', platform: 'neutral', target: 'es2022' });
await import('./licenses.mjs');
